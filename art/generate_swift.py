"""Writes Shared/CreatureArt.swift from the artwork in art.py."""
import os
from art import *

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Shared", "CreatureArt.swift")


def encode(layers):
    lines = []
    for l in layers:
        fill = l["fill"].lstrip("#") if l["fill"] else "-"
        lines.append("|".join([l["part"], l["tag"] or "-", fill, "1" if l["stroke"] else "0",
                               f'{l["width"]:g}', f'{l["opacity"]:g}', l["d"]]))
    return "\n".join(lines)


def swift_rig(stage):
    rig = STAGE_RIG[stage]
    parts = ", ".join(
        f'.{p}: PartTransform(tx: {tx}, ty: {ty}, sx: {sx}, sy: {sy}, pivot: CGPoint(x: {px}, y: {py}))'
        for p, (tx, ty, sx, sy, (px, py)) in rig["parts"].items())
    return f'StageRig(figure: {rig["figure"]}, parts: [{parts or ":"}])'


sets = {name: species(name) for name in SPECIES}
sets.update({f"{name}Asleep": curled(name) for name in SPECIES})
sets["den"] = den()

out = ["// Generated by art/generate_swift.py from art/art.py. Do not edit by hand.",
       "// Each line: part|tag|fill|stroke|width|opacity|path", "",
       "import CoreGraphics", "", "enum CreatureArt {"]
out.append(f"    static let neck = CGPoint(x: {NECK_AT[0]}, y: {NECK_AT[1]})")
out.append(f"    static let tailRoot = CGPoint(x: {TAIL_AT[0]}, y: {TAIL_AT[1]})")
out.append(f"    static let ground = CGPoint(x: {GROUND[0]}, y: {GROUND[1]})")
out.append("")
for stage in ("baby", "child", "adult"):
    out.append(f"    static let {stage}Rig = {swift_rig(stage)}")
out.append("")
for key, layers in sets.items():
    out.append(f'    static let {key} = ArtLayer.parse(#"""')
    out.append(encode(layers))
    out.append('"""#)')
    out.append("")
out.append("}")
with open(OUT, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", os.path.normpath(OUT), sum(len(v) for v in sets.values()), "layers")
